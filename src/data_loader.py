"""Dataset specs, loading and validation.

Default: California Housing (1990 US census, district level) via
`sklearn.datasets.fetch_california_housing` (needs internet on first use; scikit-learn
caches it in ~/scikit_learn_data). Target: median house value of a census block group,
converted from units of $100,000 to US dollars.

Fallback: the ORIGINAL internship synthetic generator (`--dataset synthetic`). Its prices
come from a formula, so a model trained on it is a DEMONSTRATION only.
"""

from __future__ import annotations

import logging
from dataclasses import asdict, dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd

logger = logging.getLogger(__name__)


class DatasetError(RuntimeError):
    """Dataset missing, malformed or invalid."""


@dataclass(frozen=True)
class FeatureSpec:
    name: str
    label: str
    help: str
    integer: bool = False
    min_allowed: float | None = None   # hard validation bound (None = no bound)
    max_allowed: float | None = None


@dataclass(frozen=True)
class DatasetSpec:
    key: str
    title: str
    target: str
    target_description: str
    currency: str                       # ISO code, only what the data supports
    features: tuple[FeatureSpec, ...]
    is_demo: bool = False
    notes: str = ""

    @property
    def feature_names(self) -> list[str]:
        return [f.name for f in self.features]


CALIFORNIA = DatasetSpec(
    key="california",
    title="California Housing (1990 census, block-group level)",
    target="price_usd",
    target_description="Median house value of a census block group, in US dollars (1990 values)",
    currency="USD",
    features=(
        FeatureSpec("MedInc", "Median income (in $10,000s)", "Median household income of the block group, in tens of thousands of USD.", min_allowed=0.0),
        FeatureSpec("HouseAge", "Median house age (years)", "Median age of houses in the block group.", min_allowed=0.0),
        FeatureSpec("AveRooms", "Average rooms per household", "Average number of rooms per household.", min_allowed=0.0),
        FeatureSpec("AveBedrms", "Average bedrooms per household", "Average number of bedrooms per household.", min_allowed=0.0),
        FeatureSpec("Population", "Block-group population", "Number of residents in the block group.", min_allowed=0.0),
        FeatureSpec("AveOccup", "Average occupants per household", "Average household size.", min_allowed=0.0),
        FeatureSpec("Latitude", "Latitude", "Block-group latitude (California is roughly 32.5-42.0).", min_allowed=-90.0, max_allowed=90.0),
        FeatureSpec("Longitude", "Longitude", "Block-group longitude (California is roughly -124.4 to -114.3).", min_allowed=-180.0, max_allowed=180.0),
    ),
    notes="Rows are census block groups, not individual houses. Targets are capped near $500,000.",
)

SYNTHETIC = DatasetSpec(
    key="synthetic",
    title="Synthetic demo data (original internship generator)",
    target="Price",
    target_description="Artificial price computed from a formula plus noise (demo only)",
    currency="USD",
    features=(
        FeatureSpec("Square_Footage", "Square footage", "Living area in square feet.", integer=True, min_allowed=1.0),
        FeatureSpec("Bedrooms", "Bedrooms", "Number of bedrooms.", integer=True, min_allowed=0.0),
        FeatureSpec("Age_Years", "Property age (years)", "Age of the property in years.", integer=True, min_allowed=0.0),
    ),
    is_demo=True,
    notes="Prices are generated by a known formula; metrics say nothing about real-world accuracy.",
)

SPECS = {s.key: s for s in (CALIFORNIA, SYNTHETIC)}


@dataclass
class DataReport:
    n_rows_raw: int
    n_rows_used: int
    n_missing_target_removed: int
    n_nonpositive_target_removed: int
    n_duplicate_rows_removed: int
    missing_values_per_feature: dict[str, int]
    outliers_per_feature: dict[str, int]     # |x - median| beyond 3 IQR from the quartiles (reported, not removed)
    target_min: float
    target_median: float
    target_max: float
    share_at_target_max: float               # share of rows equal to the maximum (censoring check)
    extra: dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        return asdict(self)


def make_synthetic(n: int = 100, seed: int = 42) -> pd.DataFrame:
    """Re-creation of the original internship generator (same formula), seedable."""
    rng = np.random.default_rng(seed)
    sqft = rng.integers(1000, 5000, n)
    bedrooms = rng.integers(1, 6, n)
    age = rng.integers(0, 51, n)
    price = sqft * 150 + bedrooms * 10000 - age * 2000 + rng.normal(0, 20000, n)
    return pd.DataFrame({"Square_Footage": sqft, "Bedrooms": bedrooms, "Age_Years": age, "Price": price})


def load_california() -> pd.DataFrame:
    try:
        from sklearn.datasets import fetch_california_housing

        frame = fetch_california_housing(as_frame=True).frame
    except Exception as exc:
        raise DatasetError(
            f"Could not load the California Housing dataset ({exc}).\n"
            "It needs internet access on first use. Options:\n"
            "  1. Check your connection and run again.\n"
            "  2. Provide a CSV with the same columns: --data path/to/california.csv "
            "(columns: MedInc, HouseAge, AveRooms, AveBedrms, Population, AveOccup, Latitude, Longitude, "
            "and price_usd or MedHouseVal).\n"
            "  3. Use the clearly-labelled demo fallback: --dataset synthetic"
        ) from exc
    return frame.rename(columns={"MedHouseVal": "price_usd"}).assign(
        price_usd=lambda d: d["price_usd"] * 100_000
    )


def load_csv(path: Path, spec: DatasetSpec) -> pd.DataFrame:
    path = Path(path)
    if not path.exists():
        raise DatasetError(f"Dataset file not found: {path}")
    df = pd.read_csv(path)
    if spec.key == "california" and "price_usd" not in df.columns and "MedHouseVal" in df.columns:
        df = df.assign(price_usd=df["MedHouseVal"] * 100_000)
    return df


def validate_and_clean(df: pd.DataFrame, spec: DatasetSpec) -> tuple[pd.DataFrame, DataReport]:
    """Check the schema, coerce to numeric, drop unusable rows and measure data quality.

    Outliers are *reported*, not removed: they are real districts in this data and tree
    models handle them; the linear baseline is scaled but otherwise left as-is.
    """
    needed = spec.feature_names + [spec.target]
    missing_cols = [c for c in needed if c not in df.columns]
    if missing_cols:
        raise DatasetError(f"Dataset is missing required column(s): {missing_cols}")
    if len(df) == 0:
        raise DatasetError("Dataset is empty.")

    n_raw = len(df)
    work = df[needed].apply(pd.to_numeric, errors="coerce")
    work = work.replace([np.inf, -np.inf], np.nan)

    miss_feat = {c: int(work[c].isna().sum()) for c in spec.feature_names}
    n_missing_t = int(work[spec.target].isna().sum())
    work = work[work[spec.target].notna()]
    nonpos = work[spec.target] <= 0
    n_nonpos = int(nonpos.sum())
    work = work[~nonpos]
    before = len(work)
    work = work.drop_duplicates().reset_index(drop=True)
    n_dupes = before - len(work)

    if len(work) < 50:
        raise DatasetError(f"Only {len(work)} usable rows after cleaning; need at least 50.")

    outliers = {}
    for c in spec.feature_names:
        s = work[c].dropna()
        q1, q3 = s.quantile([0.25, 0.75])
        iqr = q3 - q1
        outliers[c] = int(((s < q1 - 3 * iqr) | (s > q3 + 3 * iqr)).sum())

    t = work[spec.target]
    report = DataReport(
        n_rows_raw=n_raw, n_rows_used=len(work), n_missing_target_removed=n_missing_t,
        n_nonpositive_target_removed=n_nonpos, n_duplicate_rows_removed=n_dupes,
        missing_values_per_feature=miss_feat, outliers_per_feature=outliers,
        target_min=float(t.min()), target_median=float(t.median()), target_max=float(t.max()),
        share_at_target_max=float((t == t.max()).mean()),
    )
    return work, report


def load_dataset(kind: str = "california", path: Path | None = None, seed: int = 42):
    """Return (clean DataFrame, DataReport, DatasetSpec)."""
    if kind not in SPECS:
        raise DatasetError(f"Unknown dataset '{kind}'. Choose from {sorted(SPECS)}.")
    spec = SPECS[kind]
    if path is not None:
        raw = load_csv(path, spec)
    elif kind == "synthetic":
        raw = make_synthetic(seed=seed)
    else:
        raw = load_california()
    df, report = validate_and_clean(raw, spec)
    return df, report, spec
